        store.insert([candidate("GitHub", "alex")], addedBy: AccountProvenance.manual)
        await store.waitForPendingPersistence()

        await store.configureSync(folder: folder)
        XCTAssertEqual(store.syncStatus, .idle)
        XCTAssertEqual(store.syncHistory.first?.sourceKey, "icloud.hist.sync")
        XCTAssertEqual(store.syncFolderName, SyncFolderService.defaultFolderName)
        let uploaded = try Data(contentsOf: remoteVaultURL(in: folder))
        XCTAssertEqual(uploaded, try VaultPersistenceService.encryptedVaultData(), "Local envelope uploaded unchanged")
        XCTAssertNotNil(store.preferences.lastSyncRemoteVersion)

        XCTAssertEqual(store.syncHistory.first?.direction, .upload)

        // Neither side changed: in sync; a user-initiated "Back Up Now" records "no changes", automatic sync records nothing
        await store.sync()
        XCTAssertEqual(store.syncStatus, .idle)
        XCTAssertEqual(store.syncHistory.map(\.direction), [.unchanged, .upload])
        await store.sync(sourceKey: "icloud.hist.auto")
        XCTAssertEqual(store.syncHistory.count, 2)

        // Another device changed the remote with another master password: this device's key cannot decrypt it, so sync stops
        // without downloading or overwriting (only this device's key is accepted)
        let foreign = try foreignVaultData(password: "other device password", issuer: "Remote")
        try overwriteRemote(in: folder, with: foreign)
        await store.sync()
        XCTAssertEqual(store.syncStatus, .unreadable)
        XCTAssertEqual(store.phase, .unlocked)
        XCTAssertEqual(store.accounts.map(\.issuer), ["GitHub"])
        XCTAssertEqual(try Data(contentsOf: remoteVaultURL(in: folder)), foreign)

        // Explicit "Restore from Backup": asks for that backup's master password first; a wrong password leaves this device alone
        let localBefore = try VaultPersistenceService.encryptedVaultData()
        let wrong = await store.restoreUnreadableBackup(password: password)
        XCTAssertNotNil(wrong)
        XCTAssertEqual(store.syncStatus, .unreadable)
        XCTAssertEqual(store.phase, .unlocked)
        XCTAssertEqual(store.accounts.map(\.issuer), ["GitHub"])
        XCTAssertEqual(try VaultPersistenceService.encryptedVaultData(), localBefore, "A wrong password does not replace this device")

        // The right password replaces this device with that backup's contents and key and stays unlocked
        let restored = await store.restoreUnreadableBackup(password: "other device password")
        XCTAssertNil(restored)
        XCTAssertEqual(store.phase, .unlocked)
        XCTAssertEqual(store.syncStatus, .idle)
        XCTAssertEqual(store.accounts.map(\.issuer), ["Remote"])
        XCTAssertEqual(try VaultPersistenceService.encryptedVaultData(), foreign)
        XCTAssertEqual(store.syncHistory.first?.sourceKey, "icloud.hist.restore")

        // Later edits are saved with the new key and sync with the backup normally (envelope times have one-second precision: the
        // edit must land in a new second for the core to see a local change)
        clock.addTimeInterval(60)
        store.insert([candidate("GitLab", "sam", "MZXW6YTBOI")], addedBy: AccountProvenance.manual)
        await store.waitForPendingPersistence()
        await store.sync()
        XCTAssertEqual(store.syncStatus, .idle)
        store.lock()
        await store.unlock(password: "other device password")
        XCTAssertEqual(Set(store.accounts.map(\.issuer)), ["Remote", "GitLab"])
    }

