    func testCreateLockAndUnlockWithPassword() async {
        let store = await unlockedStore()
        XCTAssertEqual(store.phase, .unlocked)
        XCTAssertEqual(
            store.addManual(issuer: "GitHub", username: "alex", secret: "mzxw 6ytb-oi", algorithm: .sha1, digits: 6, period: 30), nil)
        await store.waitForPendingPersistence()

        store.lock()
        XCTAssertEqual(store.phase, .locked)
        XCTAssertTrue(store.accounts.isEmpty, "Locking must clear accounts from memory")

        let reopened = makeStore()
        XCTAssertEqual(reopened.phase, .locked)
        await reopened.unlock(password: "")
        XCTAssertEqual(reopened.unlockError, L10n.tr("err.vault.empty_password"), "Empty passwords are judged by the core")
        await reopened.unlock(password: password)
        XCTAssertEqual(reopened.phase, .unlocked)
        XCTAssertEqual(reopened.accounts.map(\.secret), ["MZXW6YTBOI"])
    }

    func testWrongPasswordsTriggerLockout() async {
        let store = await unlockedStore()
        store.lock()
        for _ in 0..<5 {
            await store.unlock(password: "wrong password")
        }
        XCTAssertEqual(store.phase, .locked)
        XCTAssertNotNil(store.unlockError)
        XCTAssertEqual(store.lockoutRemaining, 30)

        // During the wait even the correct password is not tried
        await store.unlock(password: password)
        XCTAssertEqual(store.phase, .locked)

        clock.addTimeInterval(31)
        await store.unlock(password: password)
        XCTAssertEqual(store.phase, .unlocked)
        XCTAssertEqual(store.preferences.consecutiveUnlockFailures, 0)
    }

    /// A corrupt file (here, KDF parameters over the limit) is not a wrong password: it fails immediately and does not count toward
    /// consecutive failures.
    func testCorruptVaultDoesNotCountAsWrongPassword() async throws {
        let store = await unlockedStore()
        store.lock()
        let url = VaultPersistenceService.vaultURL
        var envelope = try XCTUnwrap(JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        envelope["iterations"] = 4_000_000_000
        try JSONSerialization.data(withJSONObject: envelope).write(to: url)

        for _ in 0..<6 {
            await store.unlock(password: password)
        }
        XCTAssertEqual(store.phase, .locked)
        XCTAssertEqual(store.unlockError, L10n.tr("err.vault.corrupt"))
        XCTAssertEqual(store.preferences.consecutiveUnlockFailures, 0)
        XCTAssertNil(store.lockoutRemaining)
    }

    /// Main file corrupt with a last-known-good snapshot: the lock screen offers restore, and restoring with the master password
