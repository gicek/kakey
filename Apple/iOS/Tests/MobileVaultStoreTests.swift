    func testRestoreFromExportFileUsesTheChosenMasterPassword() async throws {
        let exportPassword = "Kx7-export-Qm2v"
        let masterPassword = "Kx7-master-Qm2v"
        let account = Account(issuer: "GitHub", username: "alex", secret: "JBSWY3DPEHPK3PXP", algorithm: .sha1, digits: 6, period: 30)
        let exported = try await files.exportData(accounts: [account], categories: [], password: exportPassword)
