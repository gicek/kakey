    func testCategoriesFollowMembershipMoveAndDeletion() async throws {
        let store = await unlockedStore()
        store.insert(
            [candidate("A", "a"), candidate("B", "b", "GEZDGNBVGY3TQOJQ"), candidate("C", "c", "MZXW6YTBOI")],
            addedBy: AccountProvenance.manual)
        let byIssuer = Dictionary(uniqueKeysWithValues: store.accounts.map { ($0.issuer, $0) })
        let work = try store.createCategory(named: "工作")
        XCTAssertThrowsError(try store.createCategory(named: " 工作 ")) { XCTAssertEqual($0 as? CategoryError, .duplicateName) }
        store.toggleAccount(byIssuer["A"]!.id, in: work.id)
        store.toggleAccount(byIssuer["C"]!.id, in: work.id)
        store.section = .category(work.id)
        XCTAssertEqual(store.visibleAccounts.map(\.issuer), ["A", "C"])

        store.move(fromOffsets: IndexSet(integer: 1), toOffset: 0)
        XCTAssertEqual(store.visibleAccounts.map(\.issuer), ["C", "A"])

        // iPad drag release commits in one go
        store.applyAccountOrder([byIssuer["A"]!.id, byIssuer["C"]!.id])
        XCTAssertEqual(store.visibleAccounts.map(\.issuer), ["A", "C"])

        // Categories and order persist after unlocking again
        await store.waitForPendingPersistence()
        store.lock()
        await store.unlock(password: password)
        store.section = .category(work.id)
        XCTAssertEqual(store.visibleAccounts.map(\.issuer), ["A", "C"])

        // Deleting an account removes it from categories; deleting a category keeps its accounts and returns to All
        store.delete(store.accounts.first { $0.issuer == "C" }!)
        XCTAssertEqual(store.visibleAccounts.map(\.issuer), ["A"])
        store.deleteCategory(work.id)
        XCTAssertEqual(store.section, .all)
        XCTAssertEqual(store.accounts.count, 2)
    }

