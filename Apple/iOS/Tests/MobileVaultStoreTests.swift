    /// Auto-lock counts from the last activity regardless of foreground or background. The timer uses real time, so the test only
    /// advances the injected clock and re-checks.
    func testAutoLockCountsFromLastActivity() async {
        let store = await unlockedStore()
        store.preferences.autoLock = .oneMinute
        XCTAssertNotNil(store.autoLockTask, "Timing starts right after unlock")
        clock.addTimeInterval(30)
        store.willEnterForeground()
        XCTAssertEqual(store.phase, .unlocked)

        clock.addTimeInterval(31)
        store.willEnterForeground()
        XCTAssertEqual(store.phase, .locked, "No activity since unlock: locks on returning to the foreground after 1 minute")
        XCTAssertNil(store.autoLockTask)
        XCTAssertTrue(store.autoBiometricPromptSuppressed, "After auto-lock it stays on the unlock screen without a biometric prompt")
    }

    /// Active use never locks: each activity pushes the lock time back, and it locks only after the full idle duration; activity
    /// after locking does not restart the timer.
    func testUserActivityPostponesAutoLock() async {
        let store = await unlockedStore()
        store.preferences.autoLock = .oneMinute
        for _ in 0..<5 {
            clock.addTimeInterval(50)
            store.noteUserActivity()
            store.scheduleAutoLock()
            XCTAssertEqual(store.phase, .unlocked, "More than 1 minute since unlock, but there is activity every 50 seconds")
        }

        clock.addTimeInterval(61)
        store.willEnterForeground()
        XCTAssertEqual(store.phase, .locked, "Idle for a full minute after the last activity")

        store.noteUserActivity()
        XCTAssertNil(store.lastActivityAt, "Activity while locked is not recorded")
    }

    /// Shortening the duration re-checks against the last activity: locks immediately if idle time already exceeds it; lengthening
