    private func makeStore(
        biometricsAvailable: Bool = true, cloudConnections: (any CloudConnectionStoring)? = nil
    ) -> MobileVaultStore {
        MobileVaultStore(
            settings: settings,
            keyStore: keyStore,
            clipboard: clipboard,
            authenticator: authenticator,
            biometrics: biometricsAvailable ? BiometricCapability(isAvailable: true, biometryType: .faceID) : .none,
            files: files,
            cloudConnections: cloudConnections ?? self.cloudConnections,
            httpExecutor: cloudServer,
            iCloud: iCloud,
            registerForRemoteNotifications: { [weak self] in self?.registeredForPush = true },
            now: { [clockBox] in clockBox.value }
        )
    }

    private func unlockedStore(password: String? = nil) async -> MobileVaultStore {
        let store = makeStore()
        let created = await store.createVault(password: password ?? self.password, enableBiometrics: false)
        XCTAssertTrue(created)
        return store
    }

    private func candidate(_ issuer: String, _ username: String, _ secret: String = "JBSWY3DPEHPK3PXP") -> CoreAccountCandidate {
        CoreAccountCandidate(
            issuer: issuer, username: username, secret: secret, algorithm: .sha1, digits: 6, period: 30, categoryNames: [], createdAt: nil)
    }

    /// An encrypted vault written by another device (with another master password): generated by temporarily switching the vault
    /// location, then switching back.
    private func foreignVaultData(password: String, issuer: String) throws -> Data {
        let other = FileManager.default.temporaryDirectory.appendingPathComponent(
            "KakeyMobileTests-other-\(UUID().uuidString)", isDirectory: true)
        defer {
            VaultPersistenceService.vaultURLOverride = directory.appendingPathComponent("vault.json")
            try? FileManager.default.removeItem(at: other)
        }
        VaultPersistenceService.vaultURLOverride = other.appendingPathComponent("vault.json")
        let account = Account(issuer: issuer, username: "remote", secret: "GEZDGNBVGY3TQOJQ")
        _ = try VaultPersistenceService.save(VaultContents(accounts: [account], categories: []), password: password, now: clock)
        return try VaultPersistenceService.encryptedVaultData()
    }

    private func syncFolder() throws -> URL {
        let folder = directory.appendingPathComponent("sync", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder
    }

    private func remoteVaultURL(in folder: URL) -> URL {
        folder.appendingPathComponent(SyncFolderService.defaultFolderName, isDirectory: true).appendingPathComponent(
            FolderSyncBackend.vaultFileName)
    }

    /// Simulates another device writing to the sync folder later: replaces the content and moves the modification time forward.
    private func overwriteRemote(in folder: URL, with data: Data) throws {
        let url = remoteVaultURL(in: folder)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url, options: [.atomic])
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(120)], ofItemAtPath: url.path)
    }

