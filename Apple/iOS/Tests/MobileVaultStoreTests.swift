    /// Only the lock screen after launch prompts for biometrics, once; after any lock while running (manual or automatic) it does
    /// not prompt and stays on the unlock screen.
    func testOnlyTheLaunchLockScreenAutoPromptsBiometrics() async {
        let store = await unlockedStore()
        await store.setBiometricsEnabled(true)
        await store.waitForPendingPersistence()

        store.lock()
        XCTAssertFalse(store.shouldAutoPromptBiometrics, "No prompt after a manual lock")
        await store.autoPromptBiometricsIfNeeded()
        XCTAssertEqual(store.phase, .locked)

        await store.unlockWithBiometrics()
        XCTAssertEqual(store.phase, .unlocked, "The user can still unlock by tapping the biometrics button")
        store.preferences.autoLock = .oneMinute
        clock.addTimeInterval(61)
        store.willEnterForeground()
        XCTAssertEqual(store.phase, .locked)
        XCTAssertFalse(store.shouldAutoPromptBiometrics, "No prompt after an automatic lock either")

        let launched = makeStore()
        XCTAssertEqual(launched.phase, .locked)
        XCTAssertTrue(launched.shouldAutoPromptBiometrics, "The lock screen after launch prompts once")
        await launched.autoPromptBiometricsIfNeeded()
        XCTAssertEqual(launched.phase, .unlocked)
        XCTAssertTrue(launched.autoBiometricPromptSuppressed, "No further prompts after the first")

        // The user cancels in the system prompt: stays on password entry, no message, no further automatic prompt
        let relaunched = makeStore()
        keyStore.loadError = NSError(domain: LAError.errorDomain, code: LAError.userCancel.rawValue)
        await relaunched.unlockWithBiometrics()
        XCTAssertEqual(relaunched.phase, .locked)
        XCTAssertNil(relaunched.unlockError)
        XCTAssertFalse(relaunched.shouldAutoPromptBiometrics)
    }

