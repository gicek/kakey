    /// Re-checked on becoming active: with no Touch ID at launch and a keyboard attached or a finger enrolled later, the material is
    /// saved while unlocked so Touch ID works after the next lock. Becoming unavailable again only changes the gate; it does not
    /// delete the material or change the preference.
    func testBiometricsRefreshRestoresTouchIDWithoutRestart() async {
        let hardware = Locked(false)
        let store = await unlockedStore(biometricsAvailable: false, detectBiometrics: { hardware.value })
        XCTAssertFalse(keyStore.hasKey())

        hardware.value = true
        store.refreshBiometricsAvailability()
        await store.biometricsRefreshTask?.value
        XCTAssertTrue(store.biometricsAvailable)
        XCTAssertTrue(keyStore.hasKey(), "Material should be saved once available while unlocked")
        XCTAssertTrue(store.biometricKeyAvailable)
        store.lock()
        await assertTrue(await store.unlockWithTouchID(reason: "unlock"))

        hardware.value = false
        store.refreshBiometricsAvailability()
        await store.biometricsRefreshTask?.value
        XCTAssertFalse(store.biometricsAvailable)
        XCTAssertFalse(store.biometricKeyAvailable)
        XCTAssertTrue(store.touchIDEnabled, "Temporary unavailability does not change the user preference")
        XCTAssertTrue(keyStore.hasKey(), "Temporary unavailability does not delete the material")
    }

    /// The lock screen after launch prompts for Touch ID once; after the user cancels the prompt it does not prompt again.
    func testTouchIDCancelSuppressesAutoPrompt() async {
        _ = await unlockedStore()
