/// Orchestration in `VaultStore`: every dependency is in-memory, the vault and sync folder live in a temporary directory, and the
/// clock is controllable.
@MainActor
final class VaultStoreTests: XCTestCase {
    private let password = "correct horse battery"
    private var directory: URL!
    private var iCloud: MemoryICloudVaultStore!
    private var settings: InMemorySettingsStore!
    private var keyStore: InMemoryVaultKeyStore!
    private var clipboard: RecordingClipboard!
    private var authenticator: StubBiometricAuthenticator!
    private var system: NoopSystemIntegration!
    private var files: VaultFileStore!
    /// Controllable clock; the store's `now` closure reads its current value.
    private let clockBox = Locked(Date(timeIntervalSince1970: 1_800_000_000))
    private var clock: Date {
        get { clockBox.value }
        set { clockBox.value = newValue }
    }

    private var cloudConnections: InMemoryCloudConnectionStore!
    private var cloudServer: MemoryDavExecutor!

    override func setUp() async throws {
        cloudConnections = InMemoryCloudConnectionStore()
        cloudServer = MemoryDavExecutor()
        directory = FileManager.default.temporaryDirectory.appendingPathComponent("KakeyStoreTests-\(UUID().uuidString)", isDirectory: true)
        VaultPersistenceService.vaultURLOverride = directory.appendingPathComponent("vault.json")
        settings = InMemorySettingsStore()
        keyStore = InMemoryVaultKeyStore()
        clipboard = RecordingClipboard()
        authenticator = StubBiometricAuthenticator()
        system = NoopSystemIntegration()
        files = VaultFileStore(now: { [clockBox] in clockBox.value })
        iCloud = MemoryICloudVaultStore()
    }

    override func tearDown() async throws {
        VaultPersistenceService.vaultURLOverride = nil
        try? FileManager.default.removeItem(at: directory)
    }

    private func makeStore(
        biometricsAvailable: Bool = true, detectBiometrics: (@Sendable () -> Bool)? = nil,
        cloudConnections: (any CloudConnectionStoring)? = nil
    ) -> VaultStore {
        VaultStore(
            settings: settings,
            keyStore: keyStore,
            clipboard: clipboard,
            authenticator: authenticator,
            system: system,
            biometricsAvailable: biometricsAvailable,
            detectBiometrics: detectBiometrics,
            files: files,
            iCloud: iCloud,
            cloudConnections: cloudConnections ?? self.cloudConnections,
            httpExecutor: cloudServer,
            now: { [clockBox] in clockBox.value }
        )
    }

    /// The backup currently in iCloud.
    private var remoteVault: Data? { iCloud.envelope }

    /// Simulates another device writing to iCloud: replaces the content and the record gets a new changeTag.
    private func overwriteRemote(with data: Data) throws {
        iCloud.overwrite(with: data)
    }

    private var iCloudLocation: SyncLocation { .iCloud(account: MemoryICloudVaultStore.account) }

    /// An encrypted vault written by another device (with another master password): generated by temporarily switching the vault
    /// location, then switching back.
    private func foreignVaultData(password: String, issuer: String) throws -> Data {
        let other = directory.appendingPathComponent("other-\(UUID().uuidString)", isDirectory: true)
        defer { VaultPersistenceService.vaultURLOverride = directory.appendingPathComponent("vault.json") }
        VaultPersistenceService.vaultURLOverride = other.appendingPathComponent("vault.json")
        let account = Account(issuer: issuer, username: "remote", secret: "GEZDGNBVGY3TQOJQ")
        _ = try VaultPersistenceService.save(VaultContents(accounts: [account], categories: []), password: password, now: clock)
        return try VaultPersistenceService.encryptedVaultData()
    }

    private func unlockedStore(
        biometricsAvailable: Bool = true, detectBiometrics: (@Sendable () -> Bool)? = nil
    ) async -> VaultStore {
        let store = makeStore(biometricsAvailable: biometricsAvailable, detectBiometrics: detectBiometrics)
        let created = await store.createVault(masterPassword: password)
        XCTAssertTrue(created, store.vaultError ?? "")
        return store
    }

    private func assertTrue(
        _ expression: @autoclosure () async -> Bool, _ message: String = "", file: StaticString = #filePath, line: UInt = #line
    ) async {
        let value = await expression()
        XCTAssertTrue(value, message, file: file, line: line)
    }

    private func assertFalse(
        _ expression: @autoclosure () async -> Bool, _ message: String = "", file: StaticString = #filePath, line: UInt = #line
    ) async {
        let value = await expression()
        XCTAssertFalse(value, message, file: file, line: line)
    }

    private func userFallbackError() -> NSError {
        NSError(domain: LAError.errorDomain, code: LAError.userFallback.rawValue)
    }

    // MARK: - Locking and unlocking

    func testFreshInstallStartsInOnboarding() {
        let store = makeStore()
        XCTAssertFalse(store.hasCompletedOnboarding)
        XCTAssertFalse(store.isLocked)
    }

    func testLockAndCaptureAreNoOpsBeforeOnboarding() async {
        let store = makeStore()
        store.lock()
        XCTAssertFalse(store.isLocked, "Locking without a vault must not turn the panel into the unlock form")
        XCTAssertFalse(store.autoTouchIDSuppressed)
        do {
            _ = try await store.captureQRCodeFromScreen()
            XCTFail("Screenshot scanning must not start before onboarding is complete")
        } catch {
            XCTAssertEqual(error as? VaultStore.CaptureImportError, .authorizationFailed(L10n.tr("Set up Kakey first")))
        }
    }

    func testCreateLockAndUnlockWithPassword() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.hasCompletedOnboarding)
        XCTAssertFalse(store.isLocked)
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "mzxw 6ytb-oi", algorithm: .sha1, digits: 6, period: 30))
        await store.waitForPendingPersistence()

        store.lock()
        XCTAssertTrue(store.isLocked)
        XCTAssertTrue(store.accounts.isEmpty, "Locking must clear accounts from memory")
        XCTAssertTrue(store.autoTouchIDSuppressed, "After locking while running it stays on the unlock screen without a Touch ID prompt")
        XCTAssertFalse(makeStore().autoTouchIDSuppressed, "The lock screen after launch prompts once")

        let reopened = makeStore()
        XCTAssertTrue(reopened.isLocked)
        let wrong = await reopened.unlock(password: "wrong password")
        XCTAssertFalse(wrong)
        XCTAssertEqual(reopened.vaultError, L10n.tr("err.vault.invalid_password"))
        let unlocked = await reopened.unlock(password: password)
        XCTAssertTrue(unlocked)
        XCTAssertEqual(reopened.accounts.map(\.secret), ["MZXW6YTBOI"])
    }

    func testLockClosesSheetsAndDropsQueuedRequests() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))
        let account = store.accounts[0]
        store.activeSheet = .detail(account)
        store.lock()
        XCTAssertNil(store.activeSheet, "Detail / QR code sheets hold account copies and must close on lock")
        XCTAssertTrue(store.autoTouchIDSuppressed)

        // Choosing the password in the Touch ID prompt while locked: the copy request is queued
        keyStore.loadError = userFallbackError()
        let outcome = await store.requestSecureCopy(accountID: account.id, reason: "copy")
        guard case .needsPasswordUnlock = outcome else { return XCTFail("Should queue until a password unlock") }

        // Locking again (for example, on sleep) drops the queued request so it is not fulfilled on an unrelated later unlock
        store.lock()
        _ = await store.unlock(password: password)
        XCTAssertTrue(clipboard.entries.isEmpty)
        XCTAssertNil(store.consumePendingCopyResultIssuer())
    }

    func testPendingCopyResolvesAfterPasswordUnlock() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))
        let account = store.accounts[0]
        store.lock()

        keyStore.loadError = userFallbackError()
        let outcome = await store.requestSecureCopy(accountID: account.id, reason: "copy")
        guard case .needsPasswordUnlock = outcome else { return XCTFail("Should queue until a password unlock") }
        XCTAssertTrue(store.lastTouchIDErrorWasUserFallback)
        XCTAssertTrue(store.autoTouchIDSuppressed)

        await assertTrue(await store.unlock(password: password))
        // The code is generated from real time (the pasteboard write uses `.now`)
        XCTAssertEqual(clipboard.entries.last?.text, TOTPService.code(for: account))
        XCTAssertEqual(clipboard.entries.last?.expiresAfter, 30, "Verification codes expire after the account's period")
        XCTAssertEqual(store.consumePendingCopyResultIssuer(), "GitHub")
        XCTAssertNil(store.consumePendingCopyResultIssuer())
    }

    func testSecureCopyWhileUnlockedReauthenticatesEveryTime() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 60))
        let account = store.accounts[0]

        authenticator.result = .failure(NSError(domain: LAError.errorDomain, code: LAError.userCancel.rawValue))
        guard case .failed = await store.requestSecureCopy(accountID: account.id, reason: "copy") else {
            return XCTFail("Cancel must not copy")
