        XCTAssertFalse(VaultPersistenceService.vaultExists)
        XCTAssertFalse(VaultPersistenceService.lastKnownGoodVaultExists)
        XCTAssertFalse(keyStore.hasKey())
        XCTAssertTrue(system.didResetShortcuts)
        XCTAssertTrue(store.usesCardView, "reset goes back to the default card view")
        XCTAssertFalse(makeStore().hasCompletedOnboarding)
    }

