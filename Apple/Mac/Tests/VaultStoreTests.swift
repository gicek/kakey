    // MARK: - Reset

    func testResetRequiresAuthenticationAndErasesEverything() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))
        await store.waitForPendingPersistence()
        store.usesCardView = false

        authenticator.result = .failure(NSError(domain: LAError.errorDomain, code: LAError.userCancel.rawValue))
        await assertFalse(await store.resetApplicationAfterAuthentication())
        XCTAssertTrue(store.hasCompletedOnboarding)
        XCTAssertTrue(VaultPersistenceService.vaultExists)

        authenticator.result = .success(())
