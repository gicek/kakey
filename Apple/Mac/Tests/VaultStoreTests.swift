        XCTAssertTrue(clipboard.entries.isEmpty)

        authenticator.result = .success(())
        guard case .copied(let issuer, let code) = await store.requestSecureCopy(accountID: account.id, reason: "copy") else {
            return XCTFail("Should copy")
        }
        XCTAssertEqual(issuer, "GitHub")
        XCTAssertEqual(clipboard.entries.last, RecordingClipboard.Entry(text: code, expiresAfter: 60))
        XCTAssertEqual(authenticator.requests, [.deviceOwner, .deviceOwner])
    }

