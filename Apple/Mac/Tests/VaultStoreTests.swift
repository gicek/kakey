    func testTouchIDKeyStoredOnlyWhenBiometricsAvailable() async {
        let withoutHardware = await unlockedStore(biometricsAvailable: false)
        XCTAssertTrue(withoutHardware.touchIDEnabled)
        XCTAssertFalse(keyStore.hasKey(), "A Mac without Touch ID must not store key material")
        XCTAssertFalse(withoutHardware.biometricKeyAvailable)
        withoutHardware.lock()
        await assertFalse(await withoutHardware.unlockWithTouchID(reason: "unlock"))

        try? FileManager.default.removeItem(at: directory)
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))
        await store.waitForPendingPersistence()
        XCTAssertTrue(keyStore.hasKey())
        XCTAssertTrue(store.biometricKeyAvailable)

        store.lock()
        await assertTrue(await store.unlockWithTouchID(reason: "unlock"))
        XCTAssertEqual(store.accounts.map(\.issuer), ["GitHub"])

        // Material invalidated: stays on the lock screen, deletes the material, asks for the master password
        store.lock()
        keyStore.failLoad = true
