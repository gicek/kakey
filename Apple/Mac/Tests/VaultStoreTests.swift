    /// returns.
    func testOnboardingRestoreCanChangeLocation() async throws {
        let other = await unlockedStore()
        await other.configureSync(try cloudLocation(), connection: try webDAVConnection())
        await other.waitForPendingPersistence()
        cloudConnections.remove()
        VaultPersistenceService.removeAllFiles()

        let store = makeStore()
        let found = await store.prepareOnboardingRestore(from: try cloudLocation(), connection: try webDAVConnection())
        XCTAssertEqual(found, .found)
        XCTAssertFalse(store.isFetchingOnboardingRestore)
        store.discardOnboardingRestore()
        XCTAssertNil(store.pendingOnboardingRestore)
        await assertFalse(await store.completeRestoredOnboarding(password: password))
        XCTAssertFalse(VaultPersistenceService.vaultExists)
    }

    /// When credentials cannot be stored the whole restore fails: no vault is left on this device, the next launch still shows
    /// onboarding, and nothing is overwritten by a later new vault.
    func testOnboardingRestoreLeavesNoVaultWhenTheConnectionCannotBeSaved() async throws {
        let other = await unlockedStore()
        await other.configureSync(try cloudLocation(), connection: try webDAVConnection())
        await other.waitForPendingPersistence()
        cloudConnections.remove()
        VaultPersistenceService.removeAllFiles()

        let store = makeStore(cloudConnections: FailingCloudConnectionStore())
