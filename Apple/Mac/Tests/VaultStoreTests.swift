    // MARK: - Consecutive failures

    func testWrongPasswordsTriggerLockout() async {
        let store = await unlockedStore()
        store.lock()
        for _ in 0..<5 {
            await assertFalse(await store.unlock(password: "wrong password"))
        }
        XCTAssertEqual(store.remainingLockoutSeconds(), 30)

        // During the wait even the correct password is not tried
        await assertFalse(await store.unlock(password: password))
        XCTAssertTrue(store.isLocked)
        XCTAssertEqual(store.vaultError, L10n.format("Too many attempts. Try again in %lld seconds", 30))

        clock.addTimeInterval(31)
        XCTAssertNil(store.remainingLockoutSeconds())
        await assertTrue(await store.unlock(password: password))
        XCTAssertNil(settings.object(forKey: "failedUnlockCount"), "A successful unlock resets the count")
    }

    func testCorruptVaultDoesNotCountAsWrongPasswordAndOffersLastKnownGood() async throws {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))
        await store.waitForPendingPersistence()
        store.lock()
        try Data("not a valid vault".utf8).write(to: VaultPersistenceService.vaultURL, options: [.atomic])

        for _ in 0..<6 {
            await assertFalse(await store.unlock(password: password))
        }
        XCTAssertEqual(store.vaultError, L10n.tr("err.vault.corrupt"))
        XCTAssertNil(store.remainingLockoutSeconds())
        XCTAssertTrue(store.lastKnownGoodRestoreAvailable)

        await assertFalse(await store.restoreLastKnownGoodVault(password: "wrong"))
        await assertTrue(await store.restoreLastKnownGoodVault(password: password))
        XCTAssertFalse(store.isLocked)
        XCTAssertFalse(store.lastKnownGoodRestoreAvailable)
        // The snapshot is the version before the account was added
        XCTAssertTrue(store.accounts.isEmpty)
        XCTAssertTrue(VaultPersistenceService.vaultExists)
    }

    func testDisablingLockoutDelayRequiresAuthentication() async {
        let store = await unlockedStore()
        authenticator.result = .failure(NSError(domain: LAError.errorDomain, code: LAError.userCancel.rawValue))
        await store.setLockoutDelayEnabled(false)
        XCTAssertTrue(store.lockoutDelayEnabled, "A failed authentication must not turn off the failure delay")

        authenticator.result = .success(())
        await store.setLockoutDelayEnabled(false)
        XCTAssertFalse(store.lockoutDelayEnabled)
        XCTAssertEqual(authenticator.requests, [.deviceOwner, .deviceOwner])

        store.lock()
        for _ in 0..<6 {
            await assertFalse(await store.unlock(password: "wrong password"))
        }
        XCTAssertNil(store.remainingLockoutSeconds())

        await store.setLockoutDelayEnabled(true)
        XCTAssertTrue(store.lockoutDelayEnabled)
        XCTAssertEqual(authenticator.requests.count, 2, "Turning it on needs no authentication")
    }

    // MARK: - Master password

    func testChangePasswordRekeysAndThrottlesCurrentPasswordGuesses() async {
        let store = await unlockedStore()
        XCTAssertTrue(store.addAccount(issuer: "GitHub", username: "alex", secret: "MZXW6YTBOI", algorithm: .sha1, digits: 6, period: 30))

        for _ in 0..<5 {
            await assertFalse(await store.changeMasterPassword(currentPassword: "wrong", newPassword: "new password 2026"))
        }
        XCTAssertEqual(store.remainingLockoutSeconds(), 30)
        await assertFalse(
            await store.changeMasterPassword(currentPassword: password, newPassword: "new password 2026"), "No attempt while waiting")

        clock.addTimeInterval(31)
        let reopened = makeStore()
        await assertTrue(await reopened.unlock(password: password))
        await assertTrue(await reopened.changeMasterPassword(currentPassword: password, newPassword: "new password 2026"))
        XCTAssertEqual(reopened.accounts.count, 1)
        XCTAssertFalse(reopened.isLocked)

        reopened.lock()
        await assertFalse(await reopened.unlock(password: password))
        await assertTrue(await reopened.unlock(password: "new password 2026"))
        XCTAssertEqual(reopened.accounts.map(\.issuer), ["GitHub"])
    }

    // MARK: - Auto-lock

    /// Auto-lock counts from the last activity and locks even with a window or panel open if nobody uses it. The timer uses real
    /// time, so the test only advances the injected clock and re-checks.
    func testAutoLockCountsFromLastActivityEvenWhileWindowsAreOpen() async {
        let store = await unlockedStore()
        store.autoLockMode = .oneMinute
        store.mainWindowDidOpen()
        XCTAssertNotNil(store.autoLockTask, "Timing starts right after unlock")
        XCTAssertFalse(store.isLocked)

        clock.addTimeInterval(59)
        store.scheduleAutoLock()
        XCTAssertFalse(store.isLocked)
        XCTAssertNotNil(store.autoLockTask)

        clock.addTimeInterval(2)
        store.scheduleAutoLock()
        XCTAssertTrue(store.isLocked, "Locks after a minute without activity even with the main window open")
        XCTAssertNil(store.autoLockTask)
        XCTAssertTrue(store.autoTouchIDSuppressed, "After auto-lock it stays on the unlock screen without a Touch ID prompt")

        // Closing the window does not affect timing
        await assertTrue(await store.unlock(password: password))
        store.mainWindowDidClose()
        XCTAssertFalse(store.isLocked)
        XCTAssertNotNil(store.autoLockTask)
    }

    /// Active use never locks: each activity pushes the lock time back, and it locks only after the full idle duration; activity
    /// after locking does not restart the timer.
    func testUserActivityPostponesAutoLock() async {
        let store = await unlockedStore()
        store.autoLockMode = .oneMinute
        for _ in 0..<5 {
            clock.addTimeInterval(50)
            store.noteUserActivity()
            store.scheduleAutoLock()
            XCTAssertFalse(store.isLocked, "More than 1 minute since unlock, but there is activity every 50 seconds")
        }

        clock.addTimeInterval(61)
        store.scheduleAutoLock()
        XCTAssertTrue(store.isLocked, "Idle for a full minute after the last activity")

        store.noteUserActivity()
        XCTAssertNil(store.lastActivityAt, "Activity while locked is not recorded")
    }

    /// Shortening the duration re-checks against the last activity: locks immediately if idle time already exceeds it; lengthening
    /// keeps timing.
    func testChangingAutoLockReschedulesFromLastActivity() async {
