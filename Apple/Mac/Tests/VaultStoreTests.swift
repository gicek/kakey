/// Credential store whose saves always fail (the Keychain / Secure Enclave cannot be written).
private final class FailingCloudConnectionStore: CloudConnectionStoring, @unchecked Sendable {
    func load() throws -> Data? { nil }
    func save(_ connection: Data) throws { throw CloudConnectionStoreError.unreadable }
    func remove() {}
}
