#!/usr/bin/env python3
"""Export the backup location brand icons from design/brands/*.svg.

Masters contain only viewBox 0 0 24 24 and a few <path fill d> elements. Output:
- Apple: Apple/Shared/Resources/Brands.xcassets/Brand-<Name>.imageset (vector preserved, original colors), shared by
  Mac and iOS;
- Android: Android/app/src/main/res/drawable/brand_<name>.xml (VectorDrawable, original colors).
Standard library only; run by `make icons`, and the exported files are committed.
"""

import json
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "brands"
CATALOG = ROOT / "Apple" / "Shared" / "Resources" / "Brands.xcassets"
DRAWABLE = ROOT / "Android" / "app" / "src" / "main" / "res" / "drawable"

# Master file name -> Apple asset name; Android has no iCloud.
BRANDS = {"icloud": "iCloud", "dropbox": "Dropbox", "onedrive": "OneDrive", "googledrive": "GoogleDrive", "nextcloud": "Nextcloud"}
ANDROID = ("dropbox", "onedrive", "googledrive", "nextcloud")
SVG_NS = "{http://www.w3.org/2000/svg}"
INFO = {"author": "xcode", "version": 1}


def read_paths(svg: Path) -> list[tuple[str, str]]:
    root = ET.parse(svg).getroot()
    if root.get("viewBox") != "0 0 24 24":
        raise SystemExit(f"{svg.name}: viewBox must be 0 0 24 24")
    return [(path.get("fill"), path.get("d")) for path in root.iter(f"{SVG_NS}path")]


def write_json(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2) + "\n")


def export_apple() -> None:
    shutil.rmtree(CATALOG, ignore_errors=True)
    CATALOG.mkdir(parents=True)
    write_json(CATALOG / "Contents.json", {"info": INFO})
    for key, name in BRANDS.items():
        imageset = CATALOG / f"Brand-{name}.imageset"
        imageset.mkdir()
        shutil.copyfile(SOURCE / f"{key}.svg", imageset / f"{key}.svg")
        write_json(imageset / "Contents.json", {
            "images": [{"filename": f"{key}.svg", "idiom": "universal"}],
            "info": INFO,
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "original"},
        })


def export_android() -> None:
    for key in ANDROID:
        paths = "".join(
            f'\n    <path\n        android:fillColor="{fill}"\n        android:pathData="{data}" />'
            for fill, data in read_paths(SOURCE / f"{key}.svg")
        )
        (DRAWABLE / f"brand_{key}.xml").write_text(
            "<!-- Generated by scripts/export-brand-icons.py from design/brands; do not edit by hand -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="24"\n    android:viewportHeight="24">'
            f"{paths}\n</vector>\n"
        )


if __name__ == "__main__":
    export_apple()
    export_android()
    print(f"Exported brand icons: {CATALOG.relative_to(ROOT)}, {DRAWABLE.relative_to(ROOT)}/brand_*.xml")
